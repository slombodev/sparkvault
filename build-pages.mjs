// Builds one page per game so shared links preview that game (WhatsApp, Discord, X) and Google can index it.
// Run after changing games.json or index.html:   node build-pages.mjs
//
// Writes (all generated, never edit by hand):
//   juego/<id>/index.html  copy of index.html with that game's title, description, image and JSON-LD; opens the game
//   sitemap.xml            home + every game page, to submit in Google Search Console
//   robots.txt             points crawlers to the sitemap (only read at a domain root, i.e. with a custom domain)
//   404.html               GitHub Pages fallback: a game page that wasn't built yet still opens the game
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('.', import.meta.url));
const read = (file) => readFileSync(join(ROOT, file), 'utf8');
const write = (file, text) => writeFileSync(join(ROOT, file), text);

const template = read('index.html');
const SEO_BLOCK = /<!-- seo:start[\s\S]*?<!-- seo:end -->/;
if (!SEO_BLOCK.test(template)) throw new Error('index.html is missing the <!-- seo:start --> … <!-- seo:end --> block');
const SITE = template.match(/<meta property="og:url" content="([^"]+)">/)?.[1];
if (!SITE?.endsWith('/')) throw new Error('index.html needs <meta property="og:url"> set to the site root, ending in "/"');

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const abs = (path) => new URL(path, SITE).href;
const isText = (v) => typeof v === 'string' && v.trim() !== '';
const isDate = (v) => typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v);

/** Cut at a word boundary so search results and link previews don't end mid-word. */
function summary(text, max = 160) {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (clean.length <= max) return clean;
  return `${clean.slice(0, clean.lastIndexOf(' ', max - 1)).replace(/[\s,.;:]+$/, '')}…`;
}

function jsonLd(game, url, image) {
  const dev = game.developer && isText(game.developer.name)
    ? { '@type': 'Organization', name: game.developer.name, ...(isText(game.developer.url) && { url: game.developer.url }) }
    : undefined;
  const data = {
    '@context': 'https://schema.org',
    '@type': 'VideoGame',
    name: game.title,
    description: game.description,
    url,
    image,
    genre: game.genre,
    gamePlatform: game.play ? 'Navegador web' : game.download?.platform ?? 'PC',
    ...(isDate(game.released) && { datePublished: game.released }),
    ...(dev && { author: dev, publisher: dev }),
    offers: { '@type': 'Offer', price: String(game.price ?? 0), priceCurrency: 'USD', availability: 'https://schema.org/InStock', url },
  };
  // "<" escaped so a description can never close the <script> tag.
  return JSON.stringify(data).replace(/</g, '\\u003c');
}

function gamePage(game) {
  const url = `${SITE}juego/${game.id}/`;
  const image = abs(game.background || game.cover);
  const title = game.price === 0 ? `${game.title} · Juego gratis · SparkVault` : `${game.title} · SparkVault`;
  const desc = summary(game.description);
  const block = `<!-- seo:start: generated by build-pages.mjs from games.json; edit index.html, not this file. -->
  <base href="../../">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <link rel="canonical" href="${esc(url)}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="SparkVault">
  <meta property="og:title" content="${esc(game.title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${esc(url)}">
  <meta property="og:image" content="${esc(image)}">
  <meta property="og:image:alt" content="${esc(game.title)}">
  <meta property="og:locale" content="es_LA">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="${esc(image)}">
  <script type="application/ld+json">${jsonLd(game, url, image)}</script>
  <!-- seo:end -->`;
  return template
    .replace(SEO_BLOCK, () => block)
    // Readable heading before JavaScript runs; the app fills the rest of the page.
    .replace('<h1 class="d-title" id="d-title"></h1>', () => `<h1 class="d-title" id="d-title">${esc(game.title)}</h1>`);
}

const { games } = JSON.parse(read('games.json'));
const valid = games.filter((g, i) => {
  const ok = isText(g.id) && /^[a-z0-9-]+$/.test(g.id) && isText(g.title) && isText(g.description) && isText(g.background || g.cover);
  if (!ok) console.warn(`games.json entry #${i + 1} skipped: needs id (a-z, 0-9, -), title, description and cover`);
  return ok;
});

rmSync(join(ROOT, 'juego'), { recursive: true, force: true }); // only ever holds generated pages
for (const game of valid) {
  mkdirSync(join(ROOT, 'juego', game.id), { recursive: true });
  write(`juego/${game.id}/index.html`, gamePage(game));
}

const urls = [`  <url><loc>${SITE}</loc></url>`, ...valid.map((g) =>
  `  <url><loc>${SITE}juego/${g.id}/</loc>${isDate(g.released) ? `<lastmod>${g.released}</lastmod>` : ''}</url>`)];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.join('\n')}
</urlset>
`);

write('robots.txt', `User-agent: *
Allow: /

Sitemap: ${SITE}sitemap.xml
`);

write('404.html', `<!doctype html>
<html lang="es">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
  <title>SparkVault</title>
  <script>
    // GitHub Pages serves this for any missing address. A game link opens the game inside the app.
    var m = location.pathname.match(/\\/juego\\/([a-z0-9-]+)/);
    location.replace(${JSON.stringify(SITE)} + (m ? '#/game/' + m[1] : ''));
  </script>
</head>
<body style="background:#07090f;color:#fff;font-family:system-ui,sans-serif">
  <p>Esta página no existe. <a href="${esc(SITE)}" style="color:#9fd0ff">Ir a SparkVault</a></p>
</body>
</html>
`);

console.log(`Built ${valid.length} game pages, sitemap.xml, robots.txt and 404.html for ${SITE}`);
